function budgetT(lang, key, vars) {
  let s = (BUDGET_T[lang] && BUDGET_T[lang][key]) ?? BUDGET_T.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(v);
  return s;
}
